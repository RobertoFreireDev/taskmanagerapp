export function isIconKey(key) {
  return typeof key === 'string' && Object.hasOwn(ICONS, key);
}

/** SVG markup for a task icon. Unknown keys fall back to the default icon. */
export function renderIcon(key) {
  return ICONS[isIconKey(key) ? key : DEFAULT_ICON].svg;
}

export function iconLabel(key) {
  return ICONS[isIconKey(key) ? key : DEFAULT_ICON].label;
}

export function uiIcon(name) {
  return UI_ICONS[name] ?? '';
}

/**
 * Builds the icon picker grid. Calls onPick(key) when an icon is tapped.
 * The caller decides where to show it (the task form puts it in a bottom sheet).
 */
export function iconPicker({ selected, onPick }) {
  const grid = document.createElement('div');
  grid.className = 'icon-grid';
  grid.setAttribute('role', 'listbox');
  grid.setAttribute('aria-label', 'Icons');
  for (const [key, { label, svg: markup }] of Object.entries(ICONS)) {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'icon-option';
    btn.setAttribute('role', 'option');
    btn.setAttribute('aria-selected', String(key === selected));
    btn.dataset.icon = key;
    btn.innerHTML = markup;
    const caption = document.createElement('span');
    caption.textContent = label;
    btn.append(caption);
    btn.addEventListener('click', () => onPick(key));
    grid.append(btn);
  }
  return grid;
}
